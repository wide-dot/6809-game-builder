        tfr   y,d
        addd  #$2000
        std   >clr.ldsB+2
        tfr   u,d
        addd  #clr.blockA
        std   >clr.jmpA+1
        tfr   u,d
        addd  #clr.blockB
        std   >clr.jmpB+1
        sts   >glb_register_s          ; meme convention que les sprites bdraw
        clra
        clrb
        tfr   a,dp                     ; DP=0 : il fait partie des octets pousses
        ldx   #0
        ldy   #0
        ldu   #0

