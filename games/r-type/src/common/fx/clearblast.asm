        ldu   #(NPUSH-NPUSH_FIELD)*2   ; 800 poussees : l'entree saute les 89 premieres
        bra   clr.run
playfield.clearBlastFull
        ldy   #$A000+200*40+1          ; un octet plus haut que la fin du tampon
        ldu   #0                       ; tout le deroule
clr.run
