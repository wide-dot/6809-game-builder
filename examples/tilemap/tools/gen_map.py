#!/usr/bin/env python3
"""
Generate the tilemap bench's map : src/assets/map/map-data.asm.

Not artwork : a measuring pattern, the TilemapBuffer format (map-16bits.equ)
filled from a fixed seed, so the bench reads it back cell by cell.

  - a layout of 12 x 6 chunks (768 x 768 px) twice : a byte a cell (two
    banks, ids 0-9 and 128-137) and a word a cell (three banks, ids 256-265
    too), each with its descriptor
  - 30 chunks of 8 x 8 tile entries : an empty entry one in seven, the
    others a tile index 0-15 under random flags (bit 15 the priority, bits
    11-14 solidity), bit 10 (TilemapBuffer.OPAQUE's) on one in three, as
    +OP : OP is $0400 where the option is on, 0 elsewhere (the index then)
  - the tile index : 16 records [page][routine], the routines in tiles.asm

    python3 tools/gen_map.py           # write
    python3 tools/gen_map.py --check   # exit 1 if the file is stale
"""
import os
import sys

W, H = 12, 6
CHUNKS = 10            # a bank's
TILES = 16
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'assets', 'map', 'map-data.asm')


class Lcg:
    """A fixed sequence : the map must not change between runs."""

    def __init__(self, seed):
        """Start the sequence at seed."""
        self.s = seed

    def next(self, n):
        self.s = (self.s * 1103515245 + 12345) & 0x7FFFFFFF
        return (self.s >> 16) % n


def entry(r):
    """A tile entry, as asm text."""
    if r.next(7) == 0:
        return '$0000'
    flags = (0x8000 if r.next(5) == 0 else 0) | (r.next(16) << 11)
    value = '$%04X' % (flags | r.next(TILES))
    return value + '+OP' if r.next(3) == 0 else value


def rows(items, per, op):
    """Lines of op, per items each."""
    return ['        %s   %s' % (op, ','.join(items[k:k + per])) for k in range(0, len(items), per)]


def generate():
    r = Lcg(0x5EED)
    out = ['* generated by tools/gen_map.py : do not edit', '',
           ' IFDEF TilemapBuffer.OPAQUE',
           'OP equ $0400                   ; bit 10 : the tile hides the background',
           ' ELSE',
           'OP equ 0',
           ' ENDC', '',
           'map.page equ map.RAM_OVER_CART+assets.map.page', '',
           '* the tile index : [page][routine]', 'map.tiles']
    for k in range(TILES):
        out += ['        fcb   map.page', '        fdb   tile.%d' % k]
    out += ['', '* the banks : [page][chunks]', 'map.banks']
    for b in range(3):
        out += ['        fcb   map.page', '        fdb   map.chunks%d' % b]
    out += ['', '* the layouts : [page][cells]',
            'map.bytes.layout.rec', '        fcb   map.page', '        fdb   map.bytes.layout',
            'map.words.layout.rec', '        fcb   map.page', '        fdb   map.words.layout', '']
    for name, banks, stride in (('bytes', 2, W), ('words', 3, 2 * W)):
        out += ['* a descriptor (map-16bits.equ)', 'map.%s' % name,
                '        fdb   0,0,0,0                  ; the camera limits, unread',
                '        fcb   %d,%d                     ; width, banks' % (W, banks),
                '        fdb   map.%s.layout.rec,map.banks,map.banks+3,map.tiles' % name]
        out += rows(['%d' % (k * stride) for k in range(H)], H, 'fdb') + ['']
    ids_b = [(0 if r.next(2) == 0 else 128) + r.next(CHUNKS) for _ in range(W * H)]
    out += ['map.bytes.layout'] + rows(['%d' % i for i in ids_b], W, 'fcb') + ['']
    ids_w = [r.next(3) * 128 + r.next(CHUNKS) for _ in range(W * H)]
    out += ['map.words.layout'] + rows(['%d' % i for i in ids_w], W, 'fdb') + ['']
    for b in range(3):
        out.append('map.chunks%d' % b)
        for _ in range(CHUNKS):
            out += rows([entry(r) for _ in range(64)], 8, 'fdb')
        out.append('')
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            print('stale : %s' % os.path.relpath(OUT))
            sys.exit(1)
        print('up to date')
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('written : %s' % os.path.relpath(OUT))


if __name__ == '__main__':
    main()
