package com.widedot.toolbox.graphics.spritestream;

import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;

import org.apache.commons.configuration2.tree.ImmutableNode;

import com.widedot.m6809.gamebuilder.spi.BuildContext;
import com.widedot.m6809.gamebuilder.spi.configuration.Attribute;

import lombok.extern.slf4j.Slf4j;

/**
 * Handler for the {@code <spritestream>} element : pictures as streams of
 * masked row segments, read and drawn at run time by generated walkers (a
 * manager that stores data instead of code : a sprite's bytes cost about two
 * bytes a drawn screen byte, a compiled sprite about five).
 *
 * Two forms, one shape set (the options, best set once through
 * {@code <default name="spritestream.xxx">} for both) :
 * <ul>
 * <li>with {@code <sprite>} children : each sprite's record and streams,
 * one generated source each under gendir. In an {@code <lwasm>} the element
 * yields gensource (the sources wrapped in a section, every record exported) ;
 * in an arena collection each sprite is a part the packer places ;</li>
 * <li>with {@code genwalker} : the walkers, the restore walker and their
 * tables, for the engine's {@code spritestream.asm} to call.</li>
 * </ul>
 *
 * A sprite is one picture and, optionally, the same picture moved right by
 * the 2 pixel step ({@code shifted}) : the record holds both streams, so a
 * sprite is drawn on a 2 pixel grid without shifting at run time ; with
 * mirrorable streams the mirrored facing is drawn from them as well. Record
 * (8 bytes) : stream of the picture, stream of the shifted one, their box
 * bytes N0 and N1, the height, the mirror flag (1 when the mirror of each
 * stream lands on the other's step : the picture's width is 2 mod 4).
 *
 * Every stream is decoded back (both facings when mirrorable) and compared
 * with its picture before it is written : a build never ships a stream that
 * does not draw its picture.
 */
@Slf4j
public class SpritestreamPlugin {

	/** a sprite of the element : its name and pictures */
	static final class Sprite {
		final String name;
		final Picture base;
		final Picture shifted;

		Sprite(String name, Picture base, Picture shifted) {
			this.name = name;
			this.base = base;
			this.shifted = shifted;
		}
	}

	/** a sprite encoded : the record's fields and its streams */
	static final class Encoded {
		final Sprite sprite;
		final byte[] s0;
		final byte[] s1;
		final int n0;
		final int n1;
		final int flag;

		Encoded(Sprite sprite, byte[] s0, byte[] s1, int n0, int n1, int flag) {
			this.sprite = sprite;
			this.s0 = s0;
			this.s1 = s1;
			this.n0 = n0;
			this.n1 = n1;
			this.flag = flag;
		}

		int bytes() {
			return 8 + s0.length + (s1 == null ? 0 : s1.length);
		}
	}

	public static File getFile(ImmutableNode node, BuildContext ctx) throws Exception {
		Options o = options(node, ctx);
		String genwalker = Attribute.getStringOpt(node, ctx, "genwalker");
		if (genwalker != null) {
			if (!node.getChildren().isEmpty()) {
				throw new Exception(ctx.sources.locate(node) + ": <spritestream genwalker> writes the walkers"
						+ " and takes no <sprite> : the sprites are another <spritestream> of the same options");
			}
			Walker w = new Walker(o);
			String src = w.source();
			Path path = Paths.get(ctx.path, genwalker);
			write(path, src);
			log.info("spritestream walkers : {} bytes ({} of them gaps between the aligned tables), {} record codes,"
					+ " {} restore routines ({})", w.layoutSize, w.slack, o.names.size(), w.rnames.size(), o.describe());
			return path.toFile();
		}
		String gensource = Attribute.getString(node, ctx, "gensource");
		List<String[]> parts = parts(node, ctx, o);
		String section = Attribute.getString(node, ctx, "section", "code");
		StringBuilder sb = new StringBuilder("* Generated by spritestream : the records of the sprites\n");
		for (String[] p : parts) {
			sb.append(p[1]).append(" EXPORT\n");
		}
		boolean wrap = !"none".equals(section);
		if (wrap) {
			sb.append(" SECTION ").append(section).append('\n');
		}
		for (String[] p : parts) {
			sb.append("        INCLUDE \"").append(p[0]).append("\"\n");
		}
		if (wrap) {
			sb.append(" ENDSECTION\n");
		}
		Path path = Paths.get(ctx.path, gensource);
		write(path, sb.toString());
		return path.toFile();
	}

	/** the sprites as parts : one source each, its record's symbol */
	public static List<String[]> getParts(ImmutableNode node, BuildContext ctx) throws Exception {
		if (Attribute.getStringOpt(node, ctx, "genwalker") != null) {
			throw new Exception(ctx.sources.locate(node) + ": <spritestream genwalker> is the walkers' code,"
					+ " one indivisible source : it goes in an <lwasm>, not in a collection");
		}
		return parts(node, ctx, options(node, ctx));
	}

	private static Options options(ImmutableNode node, BuildContext ctx) throws Exception {
		try {
			return Options.of(node, ctx);
		} catch (Exception e) {
			throw new Exception(ctx.sources.locate(node) + ": <spritestream> " + e.getMessage(), e);
		}
	}

	private static List<String[]> parts(ImmutableNode node, BuildContext ctx, Options o) throws Exception {
		String gendir = Attribute.getString(node, ctx, "gendir");
		String genreport = Attribute.getStringOpt(node, ctx, "genreport");
		List<Sprite> sprites = new ArrayList<Sprite>();
		for (ImmutableNode child : node.getChildren()) {
			if (!"sprite".equals(child.getNodeName())) {
				throw new Exception(ctx.sources.locate(child) + ": <" + child.getNodeName()
						+ "> is not valid inside <spritestream>, only <sprite>");
			}
			String name = Attribute.getString(child, ctx, "name");
			String file = Attribute.getString(child, ctx, "filename");
			String shifted = Attribute.getStringOpt(child, ctx, "shifted");
			Picture base = Picture.read(Paths.get(ctx.path, file).toString());
			Picture sh = shifted == null ? null : Picture.read(Paths.get(ctx.path, shifted).toString());
			sprites.add(new Sprite(name, base, sh));
		}
		if (sprites.isEmpty()) {
			throw new Exception(ctx.sources.locate(node) + ": <spritestream> has no <sprite> (and no genwalker)");
		}
		Encoder enc = new Encoder(o);
		List<String[]> parts = new ArrayList<String[]>();
		StringBuilder report = new StringBuilder("name,width,height,n0,n1,flag,stream0,stream1,record\n");
		int total = 0;
		for (Sprite s : sprites) {
			Encoded e;
			try {
				e = encode(o, enc, s);
			} catch (Exception ex) {
				throw new Exception(ctx.sources.locate(node) + ": <sprite name=\"" + s.name + "\"> " + ex.getMessage(), ex);
			}
			Path path = Paths.get(ctx.path, gendir, s.name + ".asm");
			write(path, source(o, e));
			parts.add(new String[] { path.toString(), "adr_" + s.name });
			total += e.bytes();
			report.append(s.name).append(',').append(s.base.width).append(',').append(s.base.height).append(',')
					.append(e.n0).append(',').append(e.n1).append(',').append(e.flag).append(',').append(e.s0.length)
					.append(',').append(e.s1 == null ? 0 : e.s1.length).append(',').append(e.bytes()).append('\n');
		}
		if (genreport != null) {
			write(Paths.get(ctx.path, genreport), report.toString());
		}
		log.info("spritestream : {} sprites, {} bytes of records and streams ({})", sprites.size(), total, o.describe());
		return parts;
	}

	/** a sprite's record fields and streams, each stream checked against its picture */
	static Encoded encode(Options o, Encoder enc, Sprite s) throws Exception {
		Picture b = s.base;
		if (b.height < 1 || b.height > 255) {
			throw new Exception(b.file + " is " + b.height + " rows high : 1 to 255");
		}
		if (s.shifted != null && !s.shifted.isShiftOf(b)) {
			throw new Exception(s.shifted.file + " is not " + b.file + " moved right by 2 pixels (2 transparent"
					+ " columns on the left, the same height, its width + 2)");
		}
		if (o.mirrorable && b.width % 2 != 0) {
			throw new Exception(b.file + " is " + b.width + " pixels wide : a mirrorable picture has an even width"
					+ " (a transparent column on its right), or its mirror leaves the 2 pixel grid");
		}
		int n0 = b.boxBytes();
		int n1 = s.shifted == null ? n0 : s.shifted.boxBytes();
		if (Math.max(n0, n1) > 79) {
			throw new Exception(b.file + " is " + Math.max(n0, n1) + " screen bytes wide : 79 at most");
		}
		byte[] s0 = enc.stream(b.bytes);
		Decoder.check(o, s0, b.bytes, false, b.file);
		if (o.mirrorable) {
			Decoder.check(o, s0, b.bytes, true, b.file);
		}
		byte[] s1 = null;
		if (s.shifted != null) {
			s1 = enc.stream(s.shifted.bytes);
			Decoder.check(o, s1, s.shifted.bytes, false, s.shifted.file);
			if (o.mirrorable) {
				Decoder.check(o, s1, s.shifted.bytes, true, s.shifted.file);
			}
		}
		int flag = o.mirrorable && 4 * n0 - b.width == 2 ? 1 : 0;
		return new Encoded(s, s0, s1, n0, n1, flag);
	}

	/** a sprite's part source : its record, then its streams */
	static String source(Options o, Encoded e) {
		String a = "adr_" + e.sprite.name;
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by spritestream (").append(o.describe()).append(") : ").append(e.sprite.name)
				.append(", ").append(e.sprite.base.width).append('x').append(e.sprite.base.height).append('\n');
		sb.append(a).append('\n');
		sb.append("        fdb   ").append(a).append(".s0,").append(a).append(e.s1 == null ? ".s0" : ".s1").append('\n');
		sb.append("        fcb   ").append(e.n0).append(',').append(e.n1).append(',').append(e.sprite.base.height)
				.append(',').append(e.flag).append('\n');
		bytes(sb, a + ".s0", e.s0);
		if (e.s1 != null) {
			bytes(sb, a + ".s1", e.s1);
		}
		return sb.toString();
	}

	private static void bytes(StringBuilder sb, String label, byte[] b) {
		sb.append(label).append('\n');
		for (int i = 0; i < b.length; i += 16) {
			sb.append("        fcb   ");
			for (int k = i; k < Math.min(b.length, i + 16); k++) {
				sb.append(k == i ? "" : ",").append(String.format("$%02X", b[k] & 0xFF));
			}
			sb.append('\n');
		}
	}

	private static void write(Path path, String text) throws Exception {
		if (path.getParent() != null) {
			Files.createDirectories(path.getParent());
		}
		Files.writeString(path, text);
	}
}
