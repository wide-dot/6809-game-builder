package com.widedot.toolbox.graphics.raycast;

/**
 * The generated sources of the engine's raycast capability
 * (engine/graphics/raycast). The columns unit's and the raycaster's are
 * constants and macros : the engine's file expands them where its layout
 * wants the bytes.
 */
final class Sources {

	static final String WALL = "wallscaler";
	static final String RAY = "raycast";
	/** bytes a column descriptor : page, top row, texture column, routine */
	static final int DESC = 6;

	private Sources() {
	}

	/** a routine's label */
	static String scaler(int h) {
		return WALL + ".h" + h;
	}

	/** the view, as constants */
	static String consts(Settings s) {
		Geometry g = s.geometry;
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by <wallscaler> : the view (").append(s.describe()).append(")\n");
		sb.append(WALL).append(".COLS  equ ").append(g.cols).append("        ; byte columns, 2 pixels each\n");
		sb.append(WALL).append(".ROWS  equ ").append(g.rows).append('\n');
		sb.append(WALL).append(".X     equ ").append(g.x).append("        ; its left, in byte columns\n");
		sb.append(WALL).append(".Y     equ ").append(g.y).append("        ; its top row\n");
		sb.append(WALL).append(".CEIL  equ ").append(String.format("$%02X", s.ceil * 0x11)).append('\n');
		sb.append(WALL).append(".FLOOR equ ").append(String.format("$%02X", s.floor * 0x11)).append('\n');
		sb.append(WALL).append(".DESC  equ ").append(DESC).append("        ; bytes a column descriptor\n");
		return sb.toString();
	}

	/** a routine's source : its label, its code */
	static String routine(ScalerGen.Routine r) {
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by <wallscaler> : a wall ").append(r.height).append(" rows high, ").append(r.size)
				.append(" bytes\n");
		sb.append(scaler(r.height)).append('\n');
		for (String l : r.lines) {
			sb.append(l).append('\n');
		}
		return sb.toString();
	}

	/**
	 * The columns unit's generated part : the view's constants, then
	 * _wallscaler.blocks (a block a column : pull its descriptor, restore
	 * the fringe when its wall got shorter, mount the routine's page, call
	 * it) and _wallscaler.fill (the fringe's unrolled fill and its tables).
	 */
	static String columns(Settings s) {
		Geometry g = s.geometry;
		StringBuilder sb = new StringBuilder(consts(s));
		sb.append("\n* a block a column : 41 cycles when its wall did not get shorter (puls 11,\n");
		sb.append("* cmpb 2, bls 3, stb 5, sta 5, ldu 3, jsr 7, the routine's rts 5)\n");
		sb.append("_").append(WALL).append(".blocks MACRO\n");
		for (int c = 0; c < g.cols; c++) {
			String b = WALL + ".c" + c;
			sb.append(b).append("\n        puls  a,b,x,y\n");
			sb.append("        cmpb  #0                     ; (dynamic) top row drawn last\n");
			sb.append("        bls   ").append(b).append(".d\n");
			sb.append("        jsr   ").append(WALL).append(".fringeAt\n");
			sb.append(b).append(".d\n        stb   ").append(b).append("+3\n");
			sb.append("        sta   >map.CF74021.CART\n");
			sb.append(String.format("        ldu   #$%04X\n", g.columnAddress(c)));
			sb.append("        jsr   ,y\n");
		}
		sb.append(" ENDM\n");
		int half = g.rows / 2;
		sb.append("\n* the fringe : a ceiling row and a floor row a pair (16 cycles), entered at\n");
		sb.append("* end - 8 x d ; B ceiling, A floor, X the new top row, U the row past the\n");
		sb.append("* new bottom\n");
		sb.append("_").append(WALL).append(".fill MACRO\n");
		sb.append(WALL).append(".fill\n");
		for (int i = half; i > 0; i--) {
			sb.append("        stb   >").append(-i * Geometry.STRIDE).append(",x\n");
			sb.append("        sta   >").append((i - 1) * Geometry.STRIDE).append(",u\n");
		}
		sb.append(WALL).append(".fill.end\n        rts\n");
		sb.append("* per d (rows a side, 0-").append(half).append(") : where to enter the fill\n");
		sb.append(WALL).append(".fillEntry\n");
		for (int d = 0; d <= half; d++) {
			sb.append("        fdb   ").append(WALL).append(".fill.end-").append(8 * d).append('\n');
		}
		sb.append("* per top row (0-").append(half).append(") : its offset\n");
		sb.append(WALL).append(".rowOff\n");
		for (int r = 0; r <= half; r++) {
			sb.append("        fdb   ").append(r * Geometry.STRIDE).append('\n');
		}
		sb.append(" ENDM\n");
		return sb.toString();
	}

	/** the textures, exported, in a section */
	static String textures(TextureEncoder t) {
		byte[] b = t.bytes();
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by <wallscaler> : ").append(t.count()).append(" textures, texels column-major, 64 bytes a\n");
		sb.append("* column, both nibbles the colour\n");
		sb.append(WALL).append(".textures EXPORT\n SECTION code\n").append(WALL).append(".textures\n");
		for (int i = 0; i < b.length; i += 16) {
			sb.append("        fcb   ");
			for (int k = i; k < i + 16; k++) {
				sb.append(k == i ? "" : ",").append(String.format("$%02X", b[k] & 0xFF));
			}
			sb.append('\n');
		}
		sb.append(" ENDSECTION\n");
		return sb.toString();
	}

	/** the angles, exported, in a section : 12 bytes an angle */
	static String angles(RayTables t) {
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by <raycast> : per angle (12 bytes) the first column's ray, the step\n");
		sb.append("* between columns, the direction (s1.14)\n");
		sb.append(RAY).append(".angles EXPORT\n SECTION code\n").append(RAY).append(".angles\n");
		for (int a = 0; a < RayTables.ANGLES; a++) {
			int[] v = t.angles[a];
			sb.append("        fdb   ").append(v[0]).append(',').append(v[1]).append(',').append(v[2]).append(',')
					.append(v[3]).append(',').append(t.cos(a)).append(',').append(t.sin[a]).append('\n');
		}
		sb.append(" ENDSECTION\n");
		return sb.toString();
	}

	/**
	 * The raycaster unit's generated part : its constants, the scalers and
	 * textures it names (the builder answers their pages and addresses),
	 * then _raycast.tables.
	 */
	static String tables(Settings s, RayTables t, GridMap map, int textures, int radius, boolean pair,
			String pageInclude, String pageExpr) {
		Geometry g = s.geometry;
		StringBuilder sb = new StringBuilder();
		sb.append("* Generated by <raycast> : the raycaster's tables (").append(s.describe()).append(", fov ")
				.append(g.fov).append(", map ").append(map.width).append("x").append(map.height).append(")\n");
		sb.append("        INCLUDE \"").append(pageInclude).append("\"\n");
		sb.append(RAY).append(".COLS     equ ").append(g.cols).append('\n');
		sb.append(RAY).append(".PERP_MIN equ ").append(RayTables.PERP_MIN).append("       ; the nearest a wall is seen, 8.8 cells\n");
		sb.append(RAY).append(".NLEN     equ ").append(RayTables.NLEN).append('\n');
		sb.append(RAY).append(".MAP_W    equ ").append(map.width).append('\n');
		sb.append(RAY).append(".RADIUS   equ ").append(radius).append("       ; the camera's distance to a wall, 8.8 cells\n");
		sb.append(RAY).append(".PAIR     equ ").append(pair ? 1 : 0).append("        ; 1 : an odd column between two hits of one face is their mean\n");
		for (int h : g.heights()) {
			sb.append(scaler(h)).append(" EXTERNAL\n").append(scaler(h)).append("$PAGE EXTERNAL\n");
		}
		sb.append(WALL).append(".textures EXTERNAL\n");
		sb.append("_").append(RAY).append(".tables MACRO\n");
		sb.append("* |rd| >> 4 -> 1/|rd|, 8.8 cells\n").append(RAY).append(".recip\n");
		rows(sb, "fdb", t.recip, t.recip.length, 8, "$%04X");
		sb.append("* perp >> 2 -> the height's index\n").append(RAY).append(".nsamp\n");
		rows(sb, "fcb", t.nsamp, RayTables.NLEN, 16, "%d");
		scalers(sb, g, t, pageExpr);
		sb.append("* texture number -> its address (the high byte is read : textures are at $xx00)\n");
		sb.append(RAY).append(".textures\n        fdb   0\n");
		for (int n = 0; n < textures; n++) {
			sb.append("        fdb   ").append(WALL).append(".textures+").append(n * Geometry.TEX * Geometry.TEX).append('\n');
		}
		sb.append("* the map, ").append(map.width).append(" x ").append(map.height)
				.append(", a cell = 0 or its texture number\n").append(RAY).append(".map\n");
		rows(sb, "fcb", map.cells, map.cells.length, map.width, "%d");
		sb.append(" ENDM\n");
		return sb.toString();
	}

	/** count values, some a line */
	private static void rows(StringBuilder sb, String directive, int[] values, int count, int perLine, String format) {
		for (int i = 0; i < count; i += perLine) {
			sb.append("        ").append(directive).append("   ");
			for (int k = i; k < Math.min(count, i + perLine); k++) {
				sb.append(k == i ? "" : ",").append(String.format(format, values[k]));
			}
			sb.append('\n');
		}
	}

	/** a height's index -> its scaler : 4 bytes an entry, the page and the address the builder's */
	private static void scalers(StringBuilder sb, Geometry g, RayTables t, String pageExpr) {
		sb.append("* a height's index -> the scaler's page, the top row, its address (the\n");
		sb.append("* height snapped to one a scaler exists for) : 4 bytes an entry\n").append(RAY).append(".scalers\n");
		sb.append("        fcb   0,0\n        fdb   0\n");
		for (int n = 1; n <= g.indexMax(); n++) {
			int h = t.snap[n] * g.unit();
			sb.append("        fcb   ").append(pageExpr).append(scaler(h)).append("$PAGE,").append(Math.max(0, g.topRow(h)))
					.append('\n');
			sb.append("        fdb   ").append(scaler(h)).append('\n');
		}
	}
}
