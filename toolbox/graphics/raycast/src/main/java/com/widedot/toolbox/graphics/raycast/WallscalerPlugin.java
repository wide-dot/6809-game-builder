package com.widedot.toolbox.graphics.raycast;

import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;

import org.apache.commons.configuration2.tree.ImmutableNode;

import com.widedot.m6809.gamebuilder.spi.BuildContext;
import com.widedot.m6809.gamebuilder.spi.configuration.Attribute;

import lombok.extern.slf4j.Slf4j;

/**
 * Handler for the {@code <wallscaler>} element : textured wall columns drawn
 * by compiled scalers (BM16), for the engine's
 * {@code engine/graphics/raycast}. One element a form :
 * <ul>
 * <li>{@code scalers} : a routine a wall height, one source each under
 * gendir. In an arena collection each routine is a part the packer places ;
 * in an {@code <lwasm>} gensource includes them all, exported ;</li>
 * <li>{@code columns} : the columns unit's constants and macros, to assemble
 * before the engine's {@code wallscaler.columns.asm} ;</li>
 * <li>{@code textures} : an indexed picture as texture columns ;</li>
 * <li>{@code consts} : the view's constants, for the game's own code.</li>
 * </ul>
 * The view (cols, rows, x, y, lines, clipstep, maxheight, ceil, floor) is
 * shared by every form and by {@code <raycast>} : set it once with
 * {@code <default name="raycast.xxx">}.
 */
// the toolchain signals build errors with plain Exceptions
@SuppressWarnings("PMD.AvoidThrowingRawExceptionTypes")
@Slf4j
public class WallscalerPlugin {

	public static File getFile(ImmutableNode node, BuildContext ctx) throws Exception {
		Settings s = settings(node, ctx);
		String form = Attribute.getString(node, ctx, "form");
		if ("scalers".equals(form)) {
			List<String[]> parts = scalers(node, ctx, s);
			StringBuilder sb = new StringBuilder("* Generated by <wallscaler> : the scalers\n");
			for (String[] p : parts) {
				sb.append(p[1]).append(" EXPORT\n");
			}
			sb.append(" SECTION code\n");
			for (String[] p : parts) {
				sb.append("        INCLUDE \"").append(p[0]).append("\"\n");
			}
			sb.append(" ENDSECTION\n");
			return write(ctx, Attribute.getString(node, ctx, "gensource"), sb.toString());
		}
		String gensource = Attribute.getString(node, ctx, "gensource");
		if ("columns".equals(form)) {
			return write(ctx, gensource, Sources.columns(s));
		}
		if ("consts".equals(form)) {
			return write(ctx, gensource, Sources.consts(s));
		}
		if ("textures".equals(form)) {
			String file = Attribute.getString(node, ctx, "filename");
			TextureEncoder t;
			try {
				t = TextureEncoder.read(Paths.get(ctx.path, file).toString());
			} catch (Exception e) {
				throw new Exception(ctx.sources.locate(node) + ": <wallscaler form=\"textures\"> " + e.getMessage(), e);
			}
			log.info("wallscaler textures : {} textures, {} bytes", t.count(), t.bytes().length);
			return write(ctx, gensource, Sources.textures(t));
		}
		throw new Exception(ctx.sources.locate(node) + ": <wallscaler form=\"" + form
				+ "\"> : scalers, columns, textures or consts");
	}

	/** the scalers as parts : one source a routine, its label */
	public static List<String[]> getParts(ImmutableNode node, BuildContext ctx) throws Exception {
		String form = Attribute.getString(node, ctx, "form");
		if (!"scalers".equals(form)) {
			throw new Exception(ctx.sources.locate(node) + ": <wallscaler form=\"" + form + "\"> is one indivisible"
					+ " source : it goes in an <lwasm>, only form=\"scalers\" is a collection");
		}
		return scalers(node, ctx, settings(node, ctx));
	}

	private static Settings settings(ImmutableNode node, BuildContext ctx) throws Exception {
		try {
			return Settings.of(node, ctx);
		} catch (Exception e) {
			throw new Exception(ctx.sources.locate(node) + ": <" + node.getNodeName() + "> " + e.getMessage(), e);
		}
	}

	private static List<String[]> scalers(ImmutableNode node, BuildContext ctx, Settings s) throws Exception {
		String gendir = Attribute.getString(node, ctx, "gendir");
		ScalerGen gen = new ScalerGen(s.geometry);
		List<String[]> parts = new ArrayList<String[]>();
		int bytes = 0;
		for (int h : s.geometry.heights()) {
			ScalerGen.Routine r = gen.routine(h);
			Path path = Paths.get(ctx.path, gendir, "h" + h + ".asm");
			write(path, Sources.routine(r));
			parts.add(new String[] { path.toString(), Sources.scaler(h) });
			bytes += r.size;
		}
		log.info("wallscaler scalers : {} routines, {} bytes ({})", parts.size(), bytes, s.describe());
		return parts;
	}

	static File write(BuildContext ctx, String name, String text) throws Exception {
		Path path = Paths.get(ctx.path, name);
		write(path, text);
		return path.toFile();
	}

	static void write(Path path, String text) throws Exception {
		if (path.getParent() != null) {
			Files.createDirectories(path.getParent());
		}
		Files.writeString(path, text);
	}
}
